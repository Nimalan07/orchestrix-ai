"""
Scaffolding Generator for Orchestrix Generated Projects.
Synthesizes essential runtime files (requirements, main.py, session.py, package.json, Dockerfiles, docker-compose.yml)
to ensure generated applications are complete, executable, and testable out of the box.
"""

import json
from typing import Dict, List
from app.schemas.architecture import SystemArchitecture


class ScaffoldingGenerator:
    """Generates standard project scaffolding files."""

    def generate_scaffolding(
        self,
        project_name: str,
        architecture: SystemArchitecture,
        discovered_api_routers: List[str] = None,
    ) -> Dict[str, str]:
        """
        Produce a dictionary of relative_file_path -> file_content for standard scaffolding.
        """
        slug = project_name.lower().replace(" ", "-")
        db_name = project_name.lower().replace(" ", "_").replace("-", "_") + "_db"
        routers = discovered_api_routers or []

        files: Dict[str, str] = {}

        # 1. Backend requirements.txt
        files["backend/requirements.txt"] = self._build_requirements_txt()

        # 2. Backend database session
        files["backend/app/database/session.py"] = self._build_session_py(db_name)

        # 3. Backend main.py
        files["backend/app/main.py"] = self._build_main_py(project_name, routers)

        # 4. Backend Dockerfile
        files["backend/Dockerfile"] = self._build_backend_dockerfile()

        # 5. Frontend package.json
        files["frontend/package.json"] = self._build_package_json(slug)

        # 6. Frontend tsconfig.json
        files["frontend/tsconfig.json"] = self._build_tsconfig_json()

        # 7. Frontend Dockerfile
        files["frontend/Dockerfile"] = self._build_frontend_dockerfile()

        # 8. docker-compose.yml
        files["docker-compose.yml"] = self._build_docker_compose(db_name)

        return files

    def _build_requirements_txt(self) -> str:
        return """fastapi>=0.115.0
uvicorn[standard]>=0.34.0
sqlalchemy>=2.0.0
pydantic>=2.10.0
pytest>=8.0.0
httpx>=0.28.0
python-jose[cryptography]>=3.3.0
passlib[bcrypt]>=1.7.4
bcrypt>=4.0.0
python-multipart>=0.0.9
"""

    def _build_session_py(self, db_name: str) -> str:
        return f'''"""Database engine and session management with SQLite fallback."""
import os
from sqlalchemy import create_engine
from sqlalchemy.orm import sessionmaker, declarative_base

DATABASE_URL = os.getenv("DATABASE_URL")

if not DATABASE_URL:
    # Safe default SQLite database for local execution and automated testing
    DATABASE_URL = "sqlite:///./app.db"

# Ensure SQLAlchemy postgresql dialect compatibility
if DATABASE_URL.startswith("postgres://"):
    DATABASE_URL = DATABASE_URL.replace("postgres://", "postgresql://", 1)

connect_args = {{"check_same_thread": False}} if DATABASE_URL.startswith("sqlite") else {{}}

engine = create_engine(DATABASE_URL, connect_args=connect_args)
SessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=engine)
Base = declarative_base()


def get_db():
    """Dependency that yields database session."""
    db = SessionLocal()
    try:
        yield db
    finally:
        db.close()
'''

    def _build_main_py(self, project_name: str, routers: List[str]) -> str:
        router_imports = []
        router_mounts = []

        for r in routers:
            module_name = r.replace(".py", "").replace("/", ".").replace("\\", ".")
            if module_name.startswith("backend."):
                module_name = module_name[len("backend."):]
            if module_name.startswith("app.api."):
                simple_name = module_name.split(".")[-1]
                router_imports.append(f"try:\n    from app.api.{simple_name} import router as {simple_name}_router\n    app.include_router({simple_name}_router, prefix=\"/api/{simple_name}\", tags=[\"{simple_name.capitalize()}\"])\nexcept Exception:\n    pass")

        router_block = "\n".join(router_imports) if router_imports else "# No specific routers discovered yet"

        return f'''"""
FastAPI application entry point for {project_name}.
Generated automatically by Orchestrix.
"""
from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from app.database.session import engine, Base

# Create tables on startup if not already created
try:
    Base.metadata.create_all(bind=engine)
except Exception:
    pass

app = FastAPI(
    title="{project_name} API",
    description="Backend API generated by Orchestrix Autonomous AI Software Engineer",
    version="1.0.0",
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

@app.get("/")
def read_root():
    return {{"status": "online", "project": "{project_name}"}}

@app.get("/health")
def health_check():
    return {{"status": "healthy"}}

# Auto-registered routers
{router_block}
'''

    def _build_backend_dockerfile(self) -> str:
        return """FROM python:3.13-slim

WORKDIR /app

ENV PYTHONDONTWRITEBYTECODE=1 \\
    PYTHONUNBUFFERED=1

RUN groupadd -r appgroup && useradd -r -g appgroup appuser

COPY requirements.txt .
RUN pip install --no-cache-dir -r requirements.txt

COPY . .

RUN chown -R appuser:appgroup /app
USER appuser

EXPOSE 8000

CMD ["uvicorn", "app.main:app", "--host", "0.0.0.0", "--port", "8000"]
"""

    def _build_package_json(self, slug: str) -> str:
        content = {
            "name": f"{slug}-frontend",
            "version": "0.1.0",
            "private": True,
            "scripts": {
                "dev": "next dev",
                "build": "next build",
                "start": "next start",
                "lint": "next lint"
            },
            "dependencies": {
                "next": "^14.2.0",
                "react": "^18.3.0",
                "react-dom": "^18.3.0",
                "lucide-react": "^0.450.0",
                "clsx": "^2.1.0",
                "tailwind-merge": "^2.2.0"
            },
            "devDependencies": {
                "@types/node": "^20.0.0",
                "@types/react": "^18.3.0",
                "@types/react-dom": "^18.3.0",
                "typescript": "^5.4.0",
                "tailwindcss": "^3.4.0",
                "postcss": "^8.4.0",
                "autoprefixer": "^10.4.0"
            }
        }
        return json.dumps(content, indent=2)

    def _build_tsconfig_json(self) -> str:
        content = {
            "compilerOptions": {
                "target": "es5",
                "lib": ["dom", "dom.iterable", "esnext"],
                "allowJs": True,
                "skipLibCheck": True,
                "strict": True,
                "noEmit": True,
                "esModuleInterop": True,
                "module": "esnext",
                "moduleResolution": "bundler",
                "resolveJsonModule": True,
                "isolatedModules": True,
                "jsx": "preserve",
                "incremental": True,
                "plugins": [
                    {
                        "name": "next"
                    }
                ],
                "paths": {
                    "@/*": ["./*"]
                }
            },
            "include": ["next-env.d.ts", "**/*.ts", "**/*.tsx", ".next/types/**/*.ts"],
            "exclude": ["node_modules"]
        }
        return json.dumps(content, indent=2)

    def _build_frontend_dockerfile(self) -> str:
        return """FROM node:20-alpine AS runner
WORKDIR /app
ENV NODE_ENV=production

RUN addgroup --system --gid 1001 nodejs && adduser --system --uid 1001 nextjs

COPY package.json ./
RUN npm install --omit=dev

COPY . .

USER nextjs
EXPOSE 3000
ENV PORT=3000

CMD ["npm", "run", "dev"]
"""

    def _build_docker_compose(self, db_name: str) -> str:
        return f"""version: '3.8'

services:
  backend:
    build:
      context: ./backend
      dockerfile: Dockerfile
    ports:
      - "8000:8000"
    environment:
      - DATABASE_URL=postgresql://postgres:postgres@db:5432/{db_name}
    depends_on:
      - db

  frontend:
    build:
      context: ./frontend
      dockerfile: Dockerfile
    ports:
      - "3000:3000"
    environment:
      - NEXT_PUBLIC_API_URL=http://localhost:8000
    depends_on:
      - backend

  db:
    image: postgres:16-alpine
    environment:
      POSTGRES_USER: postgres
      POSTGRES_PASSWORD: postgres
      POSTGRES_DB: {db_name}
    ports:
      - "5433:5432"
    volumes:
      - pgdata:/var/lib/postgresql/data

volumes:
  pgdata:
"""


scaffolding_generator = ScaffoldingGenerator()
